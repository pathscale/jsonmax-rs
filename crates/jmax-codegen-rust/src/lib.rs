#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum CompatibilityMode {
    #[default]
    Native,
    LegacyV1,
    LegacyV2,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CompatibilityOptions {
    pub mode: CompatibilityMode,
    pub emit_definition_variants: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CodegenOptions {
    pub module_name: String,
    pub abi_path: String,
    pub aot_path: String,
    pub derive_path: String,
    pub emit_views: bool,
    pub emit_schema_tables: bool,
    pub compatibility: CompatibilityOptions,
    /// Replacement Rust identifiers for named wire fields of nominal structs.
    pub ident_overrides: Vec<IdentOverride>,
}

/// The Rust field identifier of one wire field of one generated struct.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct IdentOverride {
    /// The PascalCase generated type name.
    pub type_name: String,
    /// The exact wire name.
    pub wire: String,
    /// A snake_case, non-keyword identifier.
    pub ident: String,
}

/// Options for the native decoder artifact.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeOptions {
    pub runtime_path: String,
    pub predict_layout: bool,
}

/// Conversion applied to one already schema-validated field in a native-first adapter.
/// Hook functions must have the shape `fn(&Source) -> Option<Target>`; returning
/// `None` reports a decode constraint violation. Hooks cannot alter schema acceptance.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ForeignConversion {
    /// Move the generated field value into the configured target field.
    Identity,
    /// Parse a validated generated string with `Target: FromStr`.
    FromStr,
    /// Convert a validated generated string with `Target: TryFrom<&str>`.
    TryFromStr,
    /// Convert a decimal/fixed-point source through a checked user hook.
    DecimalHook { function_path: String },
    /// Convert a generated enum into a custom enum or representation through a checked hook.
    EnumHook { function_path: String },
    /// Apply a checked conversion hook to any supported field type.
    CustomHook { function_path: String },
}

/// One source wire field and its destination member in a foreign target struct.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ForeignField {
    pub wire_name: String,
    pub target_field: String,
    /// A plain Rust type path, such as `::domain::AccountId`.
    pub target_type: String,
    pub conversion: ForeignConversion,
}

/// A foreign struct built from one generated native root after schema validation.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ForeignTarget {
    /// The root name as spelled in `NativeSpec.roots`.
    pub root: String,
    /// A plain Rust type path for the target struct.
    pub target_type: String,
    /// Must describe every source field exactly once.
    pub fields: Vec<ForeignField>,
}

/// Separate configuration for native-first foreign target adapters.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct NativeAdapterOptions {
    pub targets: Vec<ForeignTarget>,
}

impl Default for NativeOptions {
    fn default() -> Self {
        Self { runtime_path: String::from("::jmax_native"), predict_layout: false }
    }
}

impl Default for CodegenOptions {
    fn default() -> Self {
        Self {
            module_name: String::from("generated"), abi_path: String::from("::jmax_abi"),
            aot_path: String::from("::jmax_schema_aot"), derive_path: String::from("::jmax_derive"),
            emit_views: true, emit_schema_tables: true, compatibility: CompatibilityOptions::default(),
            ident_overrides: Vec::new(),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum ArtifactKind { ModuleRoot, Models, Endpoints, Registries, SchemaTables, Compatibility, Native }

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedArtifact {
    /// Portable relative path, always under CodegenOptions.module_name.
    pub path: String,
    pub contents: String,
    pub kind: ArtifactKind,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RegistryArtifacts {
    pub registries: GeneratedArtifact,
    pub schema_tables: GeneratedArtifact,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Generation {
    artifacts: Vec<GeneratedArtifact>,
}

impl Generation {
    pub fn artifacts(&self) -> &[GeneratedArtifact] { &self.artifacts }
    pub fn into_artifacts(self) -> Vec<GeneratedArtifact> { self.artifacts }

    /// Inserts in bytewise path order; a failure leaves the collection unchanged.
    pub fn insert(&mut self, artifact: GeneratedArtifact) -> Result<()> {
        validate_artifact_path(&artifact.path)?;
        if !artifact.contents.starts_with(GENERATED_NOTICE) {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "generated artifact lacks generation notice"));
        }
        if self.artifacts.iter().any(|item| item.path.eq_ignore_ascii_case(&artifact.path)) {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "colliding generated artifact path"));
        }
        match self.artifacts.binary_search_by(|item| item.path.cmp(&artifact.path)) {
            Ok(_) => Err(codegen_error(ErrorCode::ConstraintViolation, "duplicate generated artifact path")),
            Err(index) => { self.artifacts.insert(index, artifact); Ok(()) }
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RustTypeMode { Owned, View }

