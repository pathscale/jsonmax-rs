//! Deterministic Rust source artifacts for endpoint models. Generation never writes files.
#![cfg_attr(not(feature = "std"), no_std)]
#![forbid(unsafe_code)]

extern crate alloc;

pub use jmax_abi::error::{Error, ErrorCode, ErrorSource, Result};
pub use jmax_endpoint_model::{EndpointField, EndpointModel, EndpointSchemaSpec, EndpointType,
    EnumVariantSpec, ErrorSpec, HeaderSpec, ModelVersion, RoleSpec, ServiceSpec, TypeDefinition};
use alloc::{format, string::String, vec::Vec};

pub mod models;
pub mod endpoints;
pub mod registries;
pub mod compat;

pub const CONTRACT_VERSION: u16 = 1;
pub const GENERATED_NOTICE: &str = "// Generated by jmax-codegen-rust. Do not edit.\n";

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum CompatibilityMode {
    #[default]
    Native,
    LegacyV1,
    LegacyV2,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CompatibilityOptions {
    pub mode: CompatibilityMode,
    pub emit_definition_variants: bool,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CodegenOptions {
    pub module_name: String,
    pub abi_path: String,
    pub aot_path: String,
    pub derive_path: String,
    pub emit_views: bool,
    pub emit_schema_tables: bool,
    pub compatibility: CompatibilityOptions,
}

impl Default for CodegenOptions {
    fn default() -> Self {
        Self {
            module_name: String::from("generated"), abi_path: String::from("::jmax_abi"),
            aot_path: String::from("::jmax_schema_aot"), derive_path: String::from("::jmax_derive"),
            emit_views: true, emit_schema_tables: true, compatibility: CompatibilityOptions::default(),
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum ArtifactKind { ModuleRoot, Models, Endpoints, Registries, SchemaTables, Compatibility }

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedArtifact {
    /// Portable relative path, always under CodegenOptions.module_name.
    pub path: String,
    pub contents: String,
    pub kind: ArtifactKind,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RegistryArtifacts {
    pub registries: GeneratedArtifact,
    pub schema_tables: GeneratedArtifact,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Generation {
    artifacts: Vec<GeneratedArtifact>,
}

impl Generation {
    pub fn artifacts(&self) -> &[GeneratedArtifact] { &self.artifacts }
    pub fn into_artifacts(self) -> Vec<GeneratedArtifact> { self.artifacts }

    /// Inserts in bytewise path order; a failure leaves the collection unchanged.
    pub fn insert(&mut self, artifact: GeneratedArtifact) -> Result<()> {
        validate_artifact_path(&artifact.path)?;
        if !artifact.contents.starts_with(GENERATED_NOTICE) {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "generated artifact lacks generation notice"));
        }
        if self.artifacts.iter().any(|item| item.path.eq_ignore_ascii_case(&artifact.path)) {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "colliding generated artifact path"));
        }
        match self.artifacts.binary_search_by(|item| item.path.cmp(&artifact.path)) {
            Ok(_) => Err(codegen_error(ErrorCode::ConstraintViolation, "duplicate generated artifact path")),
            Err(index) => { self.artifacts.insert(index, artifact); Ok(()) }
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RustTypeMode { Owned, View }

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RustType {
    pub source: String,
    pub needs_lifetime: bool,
}

/// Portable relative Rust paths only. No filesystem operations or platform-dependent normalization.
pub fn validate_artifact_path(path: &str) -> Result<()> {
    if path.is_empty() || path.starts_with('/') || path.contains('\\') || !path.ends_with(".rs") {
        return Err(codegen_error(ErrorCode::ConstraintViolation, "invalid generated artifact path"));
    }
    for component in path.split('/') {
        let stem = component.split('.').next().unwrap_or("").to_ascii_uppercase();
        let device = matches!(stem.as_str(), "CON" | "PRN" | "AUX" | "NUL")
            || (stem.len() == 4 && (stem.starts_with("COM") || stem.starts_with("LPT"))
                && matches!(stem.as_bytes()[3], b'1'..=b'9'));
        if component.is_empty() || component == "." || component == ".." || component.ends_with('.') || device
            || !component.bytes().all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-' | b'.')) {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "invalid generated artifact path component"));
        }
    }
    Ok(())
}

pub fn validate_options(options: &CodegenOptions) -> Result<()> {
    jmax_schema_aot::validate_symbol(&options.module_name)?;
    validate_artifact_path(&format!("{}/mod.rs", options.module_name))?;
    jmax_schema_aot::validate_rust_path(&options.abi_path)?;
    jmax_schema_aot::validate_rust_path(&options.aot_path)?;
    jmax_schema_aot::validate_rust_path(&options.derive_path)?;
    Ok(())
}

pub fn rust_string_literal(text: &str) -> String {
    jmax_schema_aot::rust_string_literal(text)
}

pub(crate) fn codegen_error(code: ErrorCode, detail: &'static str) -> Error {
    Error::new(code, ErrorSource::SchemaCompile, 0, detail)
}

/// Generate one self-contained module tree. Module authors return source, not paths on disk.
pub fn generate(model: &EndpointModel, options: &CodegenOptions) -> Result<Generation> {
    validate_options(options)?;
    let _registry = jmax_endpoint_model::registry::build_registry(model)?;
    let mut output = Generation::default();
    output.insert(models::generate_models(model, options)?)?;
    output.insert(endpoints::generate_endpoints(model, options)?)?;
    let registry_artifacts = registries::generate_registries(model, options)?;
    output.insert(registry_artifacts.registries)?;
    output.insert(registry_artifacts.schema_tables)?;
    output.insert(compat::generate_compat(model, options)?)?;
    let contents = format!("{GENERATED_NOTICE}extern crate alloc;\npub mod models;\npub mod endpoints;\npub mod registries;\npub mod schema_tables;\npub mod compat;\n");
    output.insert(GeneratedArtifact { path: format!("{}/mod.rs", options.module_name), contents, kind: ArtifactKind::ModuleRoot })?;
    Ok(output)
}
