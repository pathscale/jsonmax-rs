/// Portable relative Rust paths only. No filesystem operations or platform-dependent normalization.
pub fn validate_artifact_path(path: &str) -> Result<()> {
    if path.is_empty() || path.starts_with('/') || path.contains('\\') || !path.ends_with(".rs") {
        return Err(codegen_error(ErrorCode::ConstraintViolation, "invalid generated artifact path"));
    }
    for component in path.split('/') {
        let stem = component.split('.').next().unwrap_or("").to_ascii_uppercase();
        let device = matches!(stem.as_str(), "CON" | "PRN" | "AUX" | "NUL")
            || (stem.len() == 4 && (stem.starts_with("COM") || stem.starts_with("LPT"))
                && matches!(stem.as_bytes()[3], b'1'..=b'9'));
        if component.is_empty() || component == "." || component == ".." || component.ends_with('.') || device
            || !component.bytes().all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-' | b'.')) {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "invalid generated artifact path component"));
        }
    }
    Ok(())
}

const RUST_KEYWORDS_FOR_IDENTS: &[&str] = &[
    "as", "async", "await", "become", "box", "break", "const", "continue", "crate", "do", "dyn",
    "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let",
    "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "union", "unsafe", "unsized", "use", "virtual", "where", "while", "yield", "abstract",
];

/// A snake_case, non-keyword identifier: ASCII lowercase, digits and underscores.
fn valid_override_ident(ident: &str) -> bool {
    let mut bytes = ident.bytes();
    matches!(bytes.next(), Some(b'a'..=b'z' | b'_'))
        && bytes.all(|byte| matches!(byte, b'a'..=b'z' | b'0'..=b'9' | b'_'))
        && ident != "_"
        && !RUST_KEYWORDS_FOR_IDENTS.contains(&ident)
}

pub fn validate_options(options: &CodegenOptions) -> Result<()> {
    jmax_schema_aot::validate_symbol(&options.module_name)?;
    validate_artifact_path(&format!("{}/mod.rs", options.module_name))?;
    jmax_schema_aot::validate_rust_path(&options.abi_path)?;
    jmax_schema_aot::validate_rust_path(&options.aot_path)?;
    jmax_schema_aot::validate_rust_path(&options.derive_path)?;
    for (index, item) in options.ident_overrides.iter().enumerate() {
        jmax_schema_aot::validate_symbol(&item.type_name)?;
        if item.wire.is_empty() || !valid_override_ident(&item.ident) {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "invalid identifier override"));
        }
        if options.ident_overrides[..index]
            .iter()
            .any(|earlier| earlier.type_name == item.type_name && earlier.wire == item.wire)
        {
            return Err(codegen_error(ErrorCode::ConstraintViolation, "identifier override repeats a field"));
        }
    }
    Ok(())
}

pub fn validate_native_options(native: &NativeOptions) -> Result<()> {
    jmax_schema_aot::validate_rust_path(&native.runtime_path)
}

pub fn rust_string_literal(text: &str) -> String {
    jmax_schema_aot::rust_string_literal(text)
}

pub(crate) fn codegen_error(code: ErrorCode, detail: &'static str) -> Error {
    Error::new(code, ErrorSource::SchemaCompile, 0, detail)
}

fn generate_shared(model: &EndpointModel, options: &CodegenOptions, native_module: bool) -> Result<Generation> {
    validate_options(options)?;
    let _registry = jmax_endpoint_model::registry::build_registry(model)?;
    let mut output = Generation::default();
    output.insert(models::generate_models(model, options)?)?;
    output.insert(endpoints::generate_endpoints(model, options)?)?;
    let registry_artifacts = registries::generate_registries(model, options)?;
    output.insert(registry_artifacts.registries)?;
    output.insert(registry_artifacts.schema_tables)?;
    output.insert(compat::generate_compat(model, options)?)?;
    let native_decl = if native_module { "pub mod native;\n" } else { "" };
    let contents = format!("{GENERATED_NOTICE}extern crate alloc;\npub mod models;\npub mod endpoints;\npub mod registries;\npub mod schema_tables;\npub mod compat;\n{native_decl}");
    output.insert(GeneratedArtifact { path: format!("{}/mod.rs", options.module_name), contents, kind: ArtifactKind::ModuleRoot })?;
    Ok(output)
}

/// Generate one self-contained module tree. Module authors return source, not paths on disk.
pub fn generate(model: &EndpointModel, options: &CodegenOptions) -> Result<Generation> {
    generate_shared(model, options, false)
}

/// The options with the specification's identifiers added as overrides. A field
/// named by both lists is a ConstraintViolation.
pub fn options_with_native_idents(options: &CodegenOptions, spec: &NativeSpec) -> Result<CodegenOptions> {
    let mut merged = options.clone();
    for ident in &spec.idents {
        merged.ident_overrides.push(IdentOverride {
            type_name: models::pascal_name(&ident.type_name)?,
            wire: ident.wire.clone(),
            ident: ident.ident.clone(),
        });
    }
    // validate_options rejects a repeated (type, wire) pair across both lists.
    validate_options(&merged)?;
    Ok(merged)
}

/// `generate`, plus `M/native.rs` and its `pub mod native;` declaration.
pub fn generate_with_native(
    model: &EndpointModel,
    spec: &NativeSpec,
    options: &CodegenOptions,
    native: &NativeOptions,
) -> Result<Generation> {
    validate_options(options)?;
    validate_native_options(native)?;
    let registry = jmax_endpoint_model::registry::build_registry(model)?;
    jmax_endpoint_model::native::validate_native_spec(&registry, spec)?;
    let merged = options_with_native_idents(options, spec)?;
    let mut output = generate_shared(model, &merged, true)?;
    output.insert(native::generate_native(model, spec, options, native)?)?;
    Ok(output)
}

/// Generate the regular native artifacts plus native-first adapters in
/// `M/native_adapters.rs`. Existing native generation remains unchanged.
pub fn generate_with_native_adapters(
    model: &EndpointModel,
    spec: &NativeSpec,
    options: &CodegenOptions,
    native: &NativeOptions,
    adapters: &NativeAdapterOptions,
) -> Result<Generation> {
    if adapters.targets.is_empty() {
        return generate_with_native(model, spec, options, native);
    }
    validate_options(options)?;
    validate_native_options(native)?;
    let registry = jmax_endpoint_model::registry::build_registry(model)?;
    jmax_endpoint_model::native::validate_native_spec(&registry, spec)?;
    native::validate_native_adapter_options(&registry, spec, options, adapters)?;
    let merged = options_with_native_idents(options, spec)?;
    let mut output = generate_shared(model, &merged, true)?;
    output.insert(native::generate_native(model, spec, options, native)?)?;
    output.insert(native::generate_native_adapters(model, spec, options, native, adapters)?)?;
    let root_path = format!("{}/mod.rs", options.module_name);
    let root = output.artifacts.iter_mut().find(|artifact| artifact.path == root_path)
        .ok_or_else(|| codegen_error(ErrorCode::InternalError, "generated module root is missing"))?;
    root.contents.push_str("pub mod native_adapters;\n");
    Ok(output)
}
